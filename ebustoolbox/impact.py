@atomic()
def attach_charging_point_types(scenario: Scenario) -> None:
    """Point the simulated Areas and Stations at their ChargingPointType.

    Runs after the simulation and before the TCO calculation, because neither target
    exists earlier: Areas are generated by ``run_eflips`` and opportunity charging is
    only visible in the Events the simulation produces.

    Mirrors the assignment rules of ``eflips.impact.utils.complete_fleet`` — depot
    charging points go to every Area with an electric charging Process, opportunity
    charging points to every Station with a ``CHARGING_OPPORTUNITY`` event — but only
    assigns foreign keys. The parameters on the rows themselves were set before the
    simulation and carried over by :func:`apply_tco_mutation`.

    :param scenario: The SIMULATION scenario, after ``apply_depot_strategy``.
    """
    charging_point_types = {
        cpt.name_short: cpt for cpt in ChargingPointType.objects.filter(scenario=scenario)
    }

    depot_cpt = charging_point_types.get(DEPOT_CPT_NAME_SHORT)
    if depot_cpt is not None:
        depot_areas = Area.objects.filter(
            scenario=scenario, processes__electric_power__isnull=False
        ).distinct()
        updated = depot_areas.update(charging_point_type=depot_cpt)
        logger.info(f"S.ID:{scenario.id}:Attached depot charging point to {updated} areas")
    else:
        logger.warning(f"S.ID:{scenario.id}:No depot ChargingPointType to attach")

    opportunity_cpt = charging_point_types.get(OPPORTUNITY_CPT_NAME_SHORT)
    if opportunity_cpt is not None:
        opportunity_station_ids = (
            Event.objects.filter(scenario=scenario, event_type="CHARGING_OPPORTUNITY")
            .exclude(station__isnull=True)
            .values_list("station_id", flat=True)
            .distinct()
        )
        updated = Station.objects.filter(
            scenario=scenario, id__in=list(opportunity_station_ids)
        ).update(charging_point_type=opportunity_cpt)
        logger.info(f"S.ID:{scenario.id}:Attached opportunity charging point to {updated} stations")
    else:
        logger.warning(f"S.ID:{scenario.id}:No opportunity ChargingPointType to attach")


