@lru_cache(maxsize=None)
def load_fleet_defaults() -> dict:
    """Return the parsed contents of ``defaults/impact/fleet.json``."""
    with open(FLEET_DEFAULTS_PATH, encoding="utf-8") as f:
        return json.load(f)


@lru_cache(maxsize=None)
def load_tco_defaults() -> dict:
    """Return the parsed contents of ``defaults/impact/tco.json``."""
    with open(TCO_DEFAULTS_PATH, encoding="utf-8") as f:
        return json.load(f)


@lru_cache(maxsize=None)
def load_lca_defaults() -> OpenLCAData:
    """Return ``defaults/impact/lca.json`` as the dataclass eflips-impact builds from.

    Parsing is not a plain ``json.load``: the loader converts the electricity factors
    from per MJ to per kWh and sums the separate production and end-of-life entries,
    so the object this returns does not have the same shape as the file.
    """
    return OpenLCAData.from_json_lca(LCA_DEFAULTS_PATH)


@lru_cache(maxsize=None)
def load_lca_overrides() -> dict:
    """Return the parsed contents of ``defaults/impact/lca_overrides.json``."""
    with open(LCA_OVERRIDES_PATH, encoding="utf-8") as f:
        return json.load(f)


def _by_name_short(entries: list[dict], key: str) -> dict[str, dict]:
    """Index a list of JSON entries by one of their string fields."""
    return {entry[key]: entry for entry in entries if entry.get(key) is not None}


def _fleet_battery_defaults() -> dict:
    """Return the specific_mass / chemistry every battery is created with."""
    entry = load_fleet_defaults()["battery_type_default"]
    return {
        "specific_mass": float(entry["specific_mass"]),
        "chemistry": entry["chemistry"],
    }


def vehicle_type_tco_defaults(vehicle_type: VehicleType) -> dict:
    """Return the default ``VehicleType.tco_parameters`` for a vehicle type.

    Energy source is the only thing that varies: there is one block for
    battery-electric vehicle types and one for diesel, and no per-model lookup. The
    upstream files key theirs by ``name_short``, which needs a fixed fleet of known
    models; the fleets here are user uploads with arbitrary names, so that list never
    matched and every vehicle type took the default regardless. A fleet that needs
    different numbers per type sets them on the costs page.
    """
    tco = load_tco_defaults()
    if vehicle_type.energy_source == EnumEnergySource.DIESEL:
        return deepcopy(tco["vehicle_type_default_diesel"])
    return deepcopy(tco["vehicle_type_default"])


def vehicle_type_tco_defaults_beb() -> dict:
    """Return the battery-electric block of ``tco.json``.

    The baseline the shared vehicle block is compared against. Unlike
    :func:`vehicle_type_tco_defaults` this takes no vehicle type, because the shared
    block belongs to no single one.
    """
    return deepcopy(load_tco_defaults()["vehicle_type_default"])


def battery_type_tco_defaults() -> dict:
    """Return the default ``BatteryType.tco_parameters``.

    One block for every battery in every scenario; see
    :func:`vehicle_type_tco_defaults` for why there is no per-vehicle-type lookup.
    """
    return deepcopy(load_tco_defaults()["battery_type_default"])


def charging_point_type_tco_defaults(name_short: str | None) -> dict:
    """Return the default ``ChargingPointType.tco_parameters`` for a charging point.

    ``name_short`` carries the depot/opportunity discriminator, because
    ChargingPointType has no column for it, and ``fleet.json`` maps it to the key
    ``tco.json`` files the defaults under. The fallback matches
    :func:`_lca_charging_point_type_overrides`: anything that is not the depot
    charging point is treated as an opportunity one.
    """
    entry = _by_name_short(load_fleet_defaults()["charging_point_types"], "name_short").get(
        name_short
    )
    if entry is not None:
        key = entry["type"]
    else:
        key = "depot" if name_short == DEPOT_CPT_NAME_SHORT else "opportunity"
    return deepcopy(load_tco_defaults()["charging_point_types"][key])


def scenario_tco_defaults() -> dict:
    """Return the default ``Scenario.tco_parameters``."""
    return deepcopy(load_tco_defaults()["scenario"])


def lifetime_defaults() -> dict:
    """Return the default lifetimes, keyed as :data:`LIFETIME_LCA_KEYS`."""
    return deepcopy(load_tco_defaults()[LIFETIMES_KEY])


def vehicle_lca_defaults(vehicle_type: VehicleType) -> dict:
    """Return the editable LCA values a vehicle type falls back on.

    The counterpart of :func:`vehicle_type_tco_defaults` for the Ökobilanz half of the
    costs page. Two values, from two different files, because that is where each of
    them already lived:

    - ``motor_rated_power_kw`` from ``lca_overrides.json``, split by energy source.
      Motor mass is derived from it as power / power-to-weight-ratio, so it drives the
      production emissions of the motor.
    - ``specific_mass`` from ``fleet.json``, in kg per kWh of gross capacity. Multiplied
      by ``VehicleType.battery_capacity`` it gives the battery mass, and with it both
      the battery's production emissions and — by subtraction from the empty mass —
      the chassis's.

    Nested under :data:`BATTERY_KEY` for the same reason the TCO block is: the two
    values land in different tables.

    :returns: ``{motor_rated_power_kw, battery: {specific_mass}}``, without the battery
        entry for a diesel vehicle type, which has none.
    """
    overrides = load_lca_overrides()
    is_diesel = vehicle_type.energy_source == EnumEnergySource.DIESEL
    key = "vehicle_type_default_diesel" if is_diesel else "vehicle_type_default"

    defaults = {MOTOR_POWER_KEY: float(overrides[key][MOTOR_POWER_KEY])}
    if not is_diesel:
        defaults[BATTERY_KEY] = {SPECIFIC_MASS_KEY: _fleet_battery_defaults()[SPECIFIC_MASS_KEY]}
    return defaults


def vehicle_lca_defaults_beb() -> dict:
    """Return the battery-electric LCA defaults, the baseline of the shared block.

    As :func:`vehicle_type_tco_defaults_beb` is for the cost values: the shared block
    belongs to no single vehicle type, so it takes no argument.
    """
    overrides = load_lca_overrides()["vehicle_type_default"]
    return {
        MOTOR_POWER_KEY: float(overrides[MOTOR_POWER_KEY]),
        BATTERY_KEY: {SPECIFIC_MASS_KEY: _fleet_battery_defaults()[SPECIFIC_MASS_KEY]},
    }


def analysis_year() -> int:
    """Return the calendar year the electricity mix is taken at.

    A constant in ``lca_overrides.json`` rather than anything derived from the
    scenario, because django-simba stores no project year: the simulated week carries
    real dates, but they are the dates of the timetable that was uploaded, not of the
    fleet being planned.

    It is the only year in the calculation. eflips-impact resolves the per-year series
    in ``lca.json`` to a single vector while the parameters are being written, and the
    calculation itself has no time dimension at all -- production is amortised into a
    per-year share and one year of driving is priced at one grid mix. See
    :func:`electricity_defaults`.
    """
    return int(load_lca_overrides()["year"])


def electricity_defaults() -> dict:
    """Return the default grid emission factors, per kWh, at :func:`analysis_year`.

    The eight categories of one impact vector, resolved out of the per-year series in
    ``lca.json`` exactly as eflips-impact would resolve it: interpolated between the
    two years bracketing the analysis year, clamped outside the range. What comes back
    is therefore what an untouched scenario is calculated with today.

    Two things about the unit are easy to trip over. The values in the file are per
    **MJ** despite the key being named ``electricity_per_kwh_by_year``, and the loader
    multiplies them by 3.6; what this returns has already been through that, so it is
    per kWh -- around 0.42 kg CO2 eq for the shipped 2025 mix, a figure that can be
    compared against a published grid factor. And these are the factors of the
    electricity *delivered to the grid connection*: the losses between there and the
    battery are applied by eflips-impact, from ``efficiency_mv_to_lv``,
    ``efficiency_lv_ac_to_dc`` and the vehicle type's charging efficiency.

    Rounded to six significant digits, because interpolating between two entries of ten
    decimal places produces a float of sixteen and every one of them would be rendered
    into an input the user is expected to read and edit. The rounding is done here
    rather than in the form so that the value shown, the value stored on save and the
    value calculated with are the same number; against the unrounded figure it is a
    relative change of at most 5e-7, five orders of magnitude below the precision of
    the ecoinvent data underneath and invisible in a chart that plots three digits.
    """
    vector = load_lca_defaults().electricity_per_kwh.at_year(analysis_year()).to_dict()
    return {category: float(f"{value:.6g}") for category, value in vector.items()}


def _lca_vehicle_type_overrides(
    vehicle_type: VehicleType, lifetimes: dict, values: dict
) -> VehicleTypeOverrides:
    """Return the per-vehicle-type LCA values that are not openLCA emission factors.

    Split by energy source only, matching :func:`vehicle_type_tco_defaults`; there is
    no per-model lookup here either.

    Consumption is left at its default of zero here and written in after the
    simulation by :func:`_write_lca_consumption`.

    :param lifetimes: From :func:`lifetime_parameters`. The lifetime is passed in
        rather than read from ``lca_overrides.json`` so that it is the same number the
        TCO writes to ``useful_life``.
    :param values: From :func:`vehicle_lca_parameters`, for the same reason: the motor
        power is the user's if they set one, and the file's only otherwise.
    """
    overrides = load_lca_overrides()
    if vehicle_type.energy_source == EnumEnergySource.DIESEL:
        entry = overrides["vehicle_type_default_diesel"]
    else:
        entry = overrides["vehicle_type_default"]

    return VehicleTypeOverrides(
        motor_rated_power_kw=float(values[MOTOR_POWER_KEY]),
        vehicle_lifetime_years=float(lifetimes["vehicle"]),
        motor_power_to_weight_ratio_kw_per_kg=entry.get("motor_power_to_weight_ratio_kw_per_kg"),
        diesel_consumption_kg_per_km=entry.get("diesel_consumption_kg_per_km"),
    )


def _lca_charging_point_type_overrides(
    name_short: str | None, lifetimes: dict
) -> ChargingPointTypeOverrides:
    """Return the LCA values for one charging point type.

    Split by depot versus opportunity, which eflips-impact's own writer does not do:
    it applies the opportunity values to every charging point type in the scenario.
    The difference is the concrete foundation, which an indoor depot charger does not
    have.

    :param lifetimes: From :func:`lifetime_parameters`, as above.
    """
    entries = load_lca_overrides()["charging_point_types"]
    entry = entries["depot"] if name_short == DEPOT_CPT_NAME_SHORT else entries["opportunity"]
    return ChargingPointTypeOverrides(
        infrastructure_lifetime_years=float(lifetimes["charging_point"]),
        foundation_volume_per_point_m3=float(entry["foundation_volume_per_point_m3"]),
    )


def tco_parameters_edited(scenario: Scenario) -> bool:
    """Return whether the user has saved the costs page for this scenario.

    Kept as a key inside ``Scenario.tco_parameters`` rather than as a column of its
    own, so no schema change is needed. eflips-impact reads that JSONB by named key
    and ignores the rest, and ``CHARGING_INFRASTRUCTURE_KEY`` already sets the
    precedent for storing something there that only django-simba understands.

    A key rather than a column also means the flag is carried by every path that
    copies the dict — :func:`apply_tco_mutation` and ``core.deepcopy`` — with no extra
    handling.

    The one place it could not live is ``Station.tco_parameters``: eflips-impact
    groups stations by the whole JSONB value, so an extra key there would change the
    grouping. Stations take their values from the scenario anyway.
    """
    return bool((scenario.tco_parameters or {}).get(USER_EDITED_KEY))


def mark_tco_parameters_edited(parameters: dict) -> dict:
    """Return ``parameters`` with the user-edited marker set."""
    return {**parameters, USER_EDITED_KEY: True}


