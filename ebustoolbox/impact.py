@atomic()
def ensure_fleet_topology(scenario: Scenario) -> None:
    """Create the fleet rows a TCO calculation needs, if the scenario has none.

    Idempotent, and safe to call on every request and again from the toolchain. It is
    called from :class:`ebustoolbox.views.CostsView` so the values it writes are on
    screen and editable before the user starts the simulation.

    Creates one :class:`~ebustoolbox.models.BatteryType` per battery-electric vehicle
    type that has none and one :class:`~ebustoolbox.models.ChargingPointType` per
    charging type. Whether it also re-seeds the ``tco_parameters`` of those rows
    depends on :func:`tco_parameters_edited`; see :func:`_seed_from_json`. Missing rows
    are always created, because the calculation cannot run without them.

    :param scenario: The scenario to complete. In the wizard this is the MUTATION.
    """
    _ensure_scenario_parameters(scenario)
    _ensure_battery_types(scenario)
    # After _ensure_battery_types, which is what creates the rows it writes to, and
    # like _ensure_station_parameters it is not gated on tco_parameters_edited by the
    # caller: it checks for itself, because it has to keep running after the user has
    # saved. That is what carries the shared values onto the SIZING scenario, where
    # the toolchain calls this again before costing.
    _apply_vehicle_common(scenario)
    _ensure_charging_point_types(scenario)
    _ensure_station_parameters(scenario)
    # Last, and unconditional: it is the only writer of useful_life on the vehicle,
    # battery and charging point rows, and the blocks the three steps above seed from
    # no longer carry one. See _apply_lifetimes.
    _apply_lifetimes(scenario)


def _seed_from_json(json_defaults: dict) -> dict:
    """Return the value to store for a row the user has not taken over.

    A replacement, not a merge: the stored dict becomes exactly the corresponding
    block of ``defaults/impact/tco.json``. That is what makes the file the only source
    of these numbers. A merge would leave whatever the column already held for keys
    the JSON does not mention — the model's ``db_default`` for a fresh row, or a value
    seeded from an earlier revision of the file — and those leftovers are invisible in
    ``tco.json`` while still reaching the calculation.

    So the ``db_default`` declared on each model is deliberately unreachable. It is
    still the column ``DEFAULT`` in Postgres, because eflips-model declares one of its
    own for the same columns and dropping Django's would not remove it; but nothing
    here reads it, and no value it writes survives the first call.

    Two invariants make the replacement safe:

    - Between ``tco.json`` and the steps that run after this one, every key
      eflips-impact reads is covered. It has no fallback: it indexes
      ``tco_parameters["useful_life"]`` and friends directly, so a key nothing fills
      is a ``KeyError`` after a full simulation has run.
    - Values that are not configured per row are written after this runs.
      :func:`_apply_lifetimes` fills in ``useful_life``, which is fleet-wide and
      shared with the LCA, and :func:`_write_energy_consumption` fills in
      ``average_electricity_consumption`` from the simulated events on the way into
      :func:`calculate_tco`.

    Callers must check :func:`tco_parameters_edited` first. Once the user has saved the
    costs page the stored numbers are theirs and nothing here may touch them.

    :param json_defaults: The corresponding block of ``defaults/impact/tco.json``.
    :returns: The value to store.
    """
    return deepcopy(json_defaults)


def _ensure_scenario_parameters(scenario: Scenario) -> None:
    """Reset ``Scenario.tco_parameters`` to ``defaults/impact/tco.json``.

    This is also what backfills keys added after a scenario was stored, such as
    ``eta_avail``, which ``TCOCalculator`` reads unconditionally.
    """
    if tco_parameters_edited(scenario):
        return

    wanted = _seed_from_json(scenario_tco_defaults())
    if wanted != scenario.tco_parameters:
        scenario.tco_parameters = wanted
        scenario.save(update_fields=["tco_parameters"])


def _adopt_battery_type(battery_type: BatteryType, scenario: Scenario) -> BatteryType:
    """Copy a BatteryType belonging to another scenario into this one.

    A vehicle type taken from the public fleet keeps that fleet's ``battery_type_id``,
    so the row it points at is shared with every other scenario that picked the same
    model. Two things go wrong with that, and both are fixed by owning a copy:

    - Everything on this page writes to the row it is shown: prices, and now the
      specific mass. On a shared row one scenario's edit would silently become
      everyone's.
    - :func:`apply_tco_mutation` remaps ``battery_type_id`` through the rows it copies
      out of the mutation, and a row belonging to a third scenario is not among them.
      ``battery_type_map.get()`` then returns ``None`` and the simulated vehicle type
      is left with no battery at all -- no battery cost, no battery emissions, and no
      error. Three simulated scenarios in this database are in exactly that state.

    Values are copied as they stand rather than re-seeded, so adopting a row changes
    nothing by itself; the steps after this one decide what it should hold.
    """
    clone = BatteryType.objects.get(id=battery_type.id)
    clone.id = None
    clone.scenario = scenario
    clone.save()
    logger.info(
        f"S.ID:{scenario.id}:Adopted BatteryType {battery_type.id} from "
        f"S.ID:{battery_type.scenario_id} as {clone.id}"
    )
    return clone


def _ensure_battery_types(scenario: Scenario) -> None:
    """Create and assign a BatteryType for every BEB vehicle type that lacks one.

    One row per vehicle type rather than one shared row: eflips-impact prices a
    battery as ``procurement_cost * VehicleType.battery_capacity``, so the parameters
    are only meaningful per vehicle type. A row that already exists but belongs to
    another scenario is copied in for the same reason; see :func:`_adopt_battery_type`.
    """
    seed_parameters = not tco_parameters_edited(scenario)

    for vehicle_type in VehicleType.objects.filter(scenario=scenario):
        update_fields = []

        if seed_parameters:
            wanted = _seed_from_json(vehicle_type_tco_defaults(vehicle_type))
            if wanted != vehicle_type.tco_parameters:
                vehicle_type.tco_parameters = wanted
                update_fields.append("tco_parameters")

        is_beb = vehicle_type.energy_source == EnumEnergySource.BATTERY_ELECTRIC
        if is_beb and vehicle_type.battery_type_id is None:
            fleet_defaults = _fleet_battery_defaults()
            battery_type = BatteryType.objects.create(
                scenario=scenario,
                specific_mass=fleet_defaults[SPECIFIC_MASS_KEY],
                chemistry=fleet_defaults["chemistry"],
                tco_parameters=battery_type_tco_defaults(),
            )
            vehicle_type.battery_type = battery_type
            update_fields.append("battery_type")
            logger.info(
                f"S.ID:{scenario.id}:Created BatteryType {battery_type.id} "
                f"for VehicleType {vehicle_type.id} ({vehicle_type.name_short})"
            )
        elif vehicle_type.battery_type_id is not None:
            battery_type = vehicle_type.battery_type
            if battery_type.scenario_id != scenario.id:
                battery_type = _adopt_battery_type(battery_type, scenario)
                vehicle_type.battery_type = battery_type
                update_fields.append("battery_type")

            if seed_parameters:
                # An existing row is re-seeded too, otherwise a battery created under an
                # older tco.json would keep those prices for good.
                wanted = _seed_from_json(battery_type_tco_defaults())
                if wanted != battery_type.tco_parameters:
                    battery_type.tco_parameters = wanted
                    battery_type.save(update_fields=["tco_parameters"])

        if update_fields:
            vehicle_type.save(update_fields=update_fields)


def _ensure_charging_point_types(scenario: Scenario) -> None:
    """Create the depot and opportunity ChargingPointType rows if they are missing.

    Both are created unconditionally. Which one is actually used is only decided
    after the simulation, in :func:`attach_charging_point_types`; an unused
    ChargingPointType contributes nothing to the TCO because eflips-impact prices it
    from the Areas and Stations pointing at it.
    """
    tco_defaults = load_tco_defaults()["charging_point_types"]
    seed_parameters = not tco_parameters_edited(scenario)

    for entry in load_fleet_defaults()["charging_point_types"]:
        # name_short carries the type, so it is the lookup key rather than a default.
        charging_point_type, created = ChargingPointType.objects.get_or_create(
            scenario=scenario,
            name_short=entry["name_short"],
            defaults={
                "name": entry["name"],
                "tco_parameters": deepcopy(tco_defaults[entry["type"]]),
            },
        )
        if created:
            logger.info(f"S.ID:{scenario.id}:Created ChargingPointType '{entry['name_short']}'")
        elif seed_parameters:
            # As for battery types: without this, a row created under an older
            # tco.json would keep those prices for good.
            wanted = _seed_from_json(tco_defaults[entry["type"]])
            if wanted != charging_point_type.tco_parameters:
                charging_point_type.tco_parameters = wanted
                charging_point_type.save(update_fields=["tco_parameters"])


def charging_infrastructure_parameters(scenario: Scenario) -> dict:
    """Return the site-build costs for this scenario, keyed ``depot`` / ``station``.

    Stored on the scenario rather than per station because the wizard has to collect
    them before it is known which station becomes a depot — the costs page runs before
    the depot page, and the :class:`~ebustoolbox.models.Depot` rows themselves are only
    created during the simulation. :func:`_ensure_station_parameters` distributes them
    onto the stations once that is settled.

    eflips-impact reads named keys out of ``Scenario.tco_parameters`` and ignores the
    rest, so keeping them there costs nothing and means they ride along with the
    existing mutation carry-over instead of needing one of their own.
    """
    defaults = load_tco_defaults()["charging_infrastructure"]
    if not tco_parameters_edited(scenario):
        return deepcopy(defaults)

    stored = (scenario.tco_parameters or {}).get(CHARGING_INFRASTRUCTURE_KEY) or {}
    return {key: {**value, **(stored.get(key) or {})} for key, value in defaults.items()}


def _webus(scenario: Scenario) -> dict:
    """Return the django-simba bookkeeping block of a scenario, possibly empty."""
    return (scenario.tco_parameters or {}).get(WEBUS_KEY) or {}


def webus_block(
    common: dict,
    overrides,
    lifetimes: dict,
    lca_common: dict,
    lca_values: dict,
    electricity: dict,
) -> dict:
    """Build the value to store under :data:`WEBUS_KEY`.

    :param common: The shared vehicle cost values, with the battery ones nested under
        :data:`BATTERY_KEY`.
    :param overrides: Keys of the vehicle types that carry their own values. One set,
        not one per calculation: a card that deviates deviates in both its cost and its
        Ökobilanz values, so the page has one checkbox for it rather than two.
    :param lifetimes: The fleet-wide lifetimes, as :func:`lifetime_parameters`.
    :param lca_common: The shared Ökobilanz values, shaped like ``common``; see
        :func:`vehicle_lca_defaults`.
    :param lca_values: ``{vehicle key: block}`` for the vehicle types that deviate,
        shaped as ``lca_common``. Unlike their cost counterparts these cannot live on
        the row -- see :data:`MOTOR_POWER_KEY`.
    :param electricity: The grid emission factors, one impact vector for the whole
        scenario; see :func:`electricity_parameters`.
    """
    return {
        VEHICLE_COMMON_KEY: common,
        VEHICLE_OVERRIDES_KEY: sorted(overrides),
        LIFETIMES_KEY: lifetimes,
        LCA_COMMON_KEY: lca_common,
        LCA_OVERRIDES_KEY: lca_values,
        ELECTRICITY_KEY: electricity,
    }


def vehicle_common_parameters(scenario: Scenario) -> dict:
    """Return the values every battery-electric vehicle type follows by default.

    The counterpart of :func:`charging_infrastructure_parameters` for vehicles, and
    the same overlay: the JSON defaults until the user has saved the costs page, then
    the JSON defaults with the stored block laid over them, so a key added to
    ``tco.json`` afterwards still resolves.

    Battery values are nested under :data:`BATTERY_KEY` rather than kept beside the
    vehicle ones. They land in a different table, so a flat block would collide on
    ``procurement_cost``, which both rows have.

    Only battery-electric vehicle types can follow this. ``tco.json`` prices a diesel
    bus at 250 000 € against 550 000 € for an electric one, so a single shared block
    across a mixed fleet would be wrong for one of them; diesel types always carry
    their own values. See :func:`follows_common`.

    Lifetimes are not here even though they too are shared. They are shared more
    widely — a diesel type follows them as well, and so does the LCA — so they are
    their own block; see :func:`lifetime_parameters`.

    :returns: ``{procurement_cost, cost_escalation, battery: {...}}``.
    """
    beb = vehicle_type_tco_defaults_beb()
    defaults = {key: beb[key] for key in VEHICLE_COMMON_FIELDS}
    defaults[BATTERY_KEY] = battery_type_tco_defaults()

    if not tco_parameters_edited(scenario):
        return deepcopy(defaults)

    stored = _webus(scenario).get(VEHICLE_COMMON_KEY) or {}
    common = {**defaults, **{k: v for k, v in stored.items() if k != BATTERY_KEY}}
    common[BATTERY_KEY] = {**defaults[BATTERY_KEY], **(stored.get(BATTERY_KEY) or {})}
    return common


def lifetime_parameters(scenario: Scenario) -> dict:
    """Return the lifetimes this scenario amortises over, in years.

    The one set of numbers both calculations use. The TCO writes each of them to a
    ``useful_life`` and the LCA to the key :data:`LIFETIME_LCA_KEYS` names, but there
    is a single value behind each pair and a single input for it on the costs page.

    Before this existed the two halves were filled from different files and had
    drifted: ``tco.json`` wrote a bus off over 14 years and ``lca_overrides.json`` over
    12, a battery over 7 against ``lca.json``'s 8. eflips-impact checks the battery
    pair itself (``lca/calculation.py:196``) and warned on every LCA run.

    Same overlay as :func:`vehicle_common_parameters`: the JSON defaults until the
    user has saved the costs page, then the defaults with the stored block laid over
    them, so a key added to ``tco.json`` afterwards still resolves.

    Stored inside :data:`WEBUS_KEY` rather than in a column of its own. There is no
    ``Scenario.lca_parameters`` to put a shared value in, adding one would be a schema
    change, and everything already in that key rides the mutation carry-over and the
    deepcopy onto the simulated scenarios for free.

    :returns: ``{vehicle, battery, charging_point}``, all in years.
    """
    defaults = lifetime_defaults()
    if not tco_parameters_edited(scenario):
        return defaults

    stored = _webus(scenario).get(LIFETIMES_KEY) or {}
    return {**defaults, **{k: v for k, v in stored.items() if k in defaults}}


def _apply_lifetimes(scenario: Scenario) -> None:
    """Write the scenario's lifetimes onto every row that needs one.

    The last step of :func:`ensure_fleet_topology`, and the only writer of
    ``useful_life`` on these three tables. It runs whether or not the user has saved,
    because the blocks in ``tco.json`` no longer carry a ``useful_life`` of their own:
    :func:`_seed_from_json` replaces a row wholesale, so without this every seeded row
    would reach eflips-impact a key short and raise.

    Merged rather than assigned, like :func:`_apply_vehicle_common`, so the prices
    just seeded beside it survive.

    Stations are not touched. Their ``useful_life`` is the life of the site rather
    than of any hardware the LCA models, it has nothing to agree with, and
    :func:`charging_infrastructure_parameters` still carries it.
    """
    lifetimes = lifetime_parameters(scenario)

    def stamp(row, years) -> None:
        wanted = {**(row.tco_parameters or {}), "useful_life": years}
        if wanted != row.tco_parameters:
            row.tco_parameters = wanted
            row.save(update_fields=["tco_parameters"])

    for vehicle_type in VehicleType.objects.filter(scenario=scenario):
        stamp(vehicle_type, lifetimes["vehicle"])
        if vehicle_type.battery_type_id is not None:
            stamp(vehicle_type.battery_type, lifetimes["battery"])

    for charging_point_type in ChargingPointType.objects.filter(scenario=scenario):
        stamp(charging_point_type, lifetimes["charging_point"])


def vehicle_overrides(scenario: Scenario) -> set:
    """Return the keys of the vehicle types that carry their own values.

    Keyed by :func:`vehicle_key` rather than by row id, because the simulated
    scenarios are deepcopies and the same vehicle type has a different id in each.
    """
    return set(_webus(scenario).get(VEHICLE_OVERRIDES_KEY) or [])


def follows_common(vehicle_type: VehicleType, overrides: set) -> bool:
    """Return whether a vehicle type takes its values from the shared block.

    :param overrides: The set from :func:`vehicle_overrides`.
    """
    if vehicle_type.energy_source == EnumEnergySource.DIESEL:
        return False
    return vehicle_key(vehicle_type) not in overrides


def _apply_vehicle_common(scenario: Scenario) -> None:
    """Copy the shared vehicle block down onto the rows that follow it.

    The same move :func:`_ensure_station_parameters` makes for stations, and for the
    same reason: eflips-impact reads one complete dict per row and knows nothing about
    inheritance, so whatever the user shares has to be materialised before it runs.

    Merged rather than assigned, so keys the block does not cover survive — most
    importantly ``average_electricity_consumption``, which is written per row after
    the simulation by :func:`_write_energy_consumption`.

    Rows that deviate are not touched: their values are their own, and the costs page
    is the only thing that writes them.
    """
    if not tco_parameters_edited(scenario):
        return

    common = vehicle_common_parameters(scenario)
    battery_common = common.get(BATTERY_KEY) or {}
    vehicle_common = {key: value for key, value in common.items() if key != BATTERY_KEY}
    overrides = vehicle_overrides(scenario)

    for vehicle_type in VehicleType.objects.filter(scenario=scenario):
        if not follows_common(vehicle_type, overrides):
            continue

        wanted = {**(vehicle_type.tco_parameters or {}), **vehicle_common}
        if wanted != vehicle_type.tco_parameters:
            vehicle_type.tco_parameters = wanted
            vehicle_type.save(update_fields=["tco_parameters"])

        if vehicle_type.battery_type_id is None:
            continue
        battery_type = vehicle_type.battery_type
        wanted = {**(battery_type.tco_parameters or {}), **battery_common}
        if wanted != battery_type.tco_parameters:
            battery_type.tco_parameters = wanted
            battery_type.save(update_fields=["tco_parameters"])


def _merge_lca_block(defaults: dict, stored: dict) -> dict:
    """Lay a stored Ökobilanz block over its defaults, one level of nesting deep."""
    merged = {**defaults, **{k: v for k, v in stored.items() if k != BATTERY_KEY}}
    if BATTERY_KEY in defaults:
        merged[BATTERY_KEY] = {**defaults[BATTERY_KEY], **(stored.get(BATTERY_KEY) or {})}
    return merged


def lca_common_parameters(scenario: Scenario) -> dict:
    """Return the Ökobilanz values every battery-electric vehicle type follows.

    The counterpart of :func:`vehicle_common_parameters` for the environmental half of
    the costs page, with the same overlay over :func:`vehicle_lca_defaults_beb`.

    Only battery-electric types can follow it, for the same reason as there: a diesel
    bus has no battery, so half the block would be meaningless for it. Diesel types
    always carry their own motor power. See :func:`follows_common`.

    :returns: ``{motor_rated_power_kw, battery: {specific_mass}}``.
    """
    defaults = vehicle_lca_defaults_beb()
    if not tco_parameters_edited(scenario):
        return defaults
    return _merge_lca_block(defaults, _webus(scenario).get(LCA_COMMON_KEY) or {})


def vehicle_lca_parameters(scenario: Scenario, vehicle_type: VehicleType) -> dict:
    """Return the Ökobilanz values one vehicle type is calculated with.

    The single resolver behind both editable LCA inputs: the shared block for a type
    that follows it, its own stored block otherwise, and the JSON defaults underneath
    either. Everything that writes an LCA value reads it from here, so the number on
    the costs page and the number in the calculation cannot come apart.

    Deviating values are read from the scenario rather than from the row, which is
    where the cost values of a deviating type live. Neither of these two could survive
    there: :func:`ensure_lca_parameters` replaces ``lca_parameters`` wholesale on every
    run, and ``specific_mass`` is a plain column that the same function overwrites.

    :returns: ``{motor_rated_power_kw, battery: {specific_mass}}``, without the battery
        entry for a diesel vehicle type.
    """
    if follows_common(vehicle_type, vehicle_overrides(scenario)):
        return lca_common_parameters(scenario)

    defaults = vehicle_lca_defaults(vehicle_type)
    if not tco_parameters_edited(scenario):
        return defaults

    stored = (_webus(scenario).get(LCA_OVERRIDES_KEY) or {}).get(vehicle_key(vehicle_type)) or {}
    return _merge_lca_block(defaults, stored)


def electricity_parameters(scenario: Scenario) -> dict:
    """Return the grid emission factors this scenario charges at, per kWh.

    One impact vector, the same overlay over :func:`electricity_defaults` as everywhere
    else on this page. It describes the electricity rather than the fleet, so it is
    scenario-wide: there is no per-vehicle-type version of it, and a mixed fleet's
    diesel types are unaffected -- their factors are ``diesel_per_kg``, which is not
    editable.

    Stored as the vector alone, with no year beside it. ``lca.json`` holds a series of
    years because the study it comes from projected one, but eflips-impact samples that
    series exactly once, at :func:`analysis_year`, and everything downstream sees only
    the resulting vector. A scenario that carries its own values therefore needs only
    that one vector, and :func:`ensure_lca_parameters` hands it over as a one-entry
    series, where the sampling is an exact lookup rather than an interpolation.

    :returns: The eight categories of :class:`DefaultImpactVector`, per kWh delivered
        to the grid connection.
    """
    defaults = electricity_defaults()
    if not tco_parameters_edited(scenario):
        return defaults

    stored = _webus(scenario).get(ELECTRICITY_KEY) or {}
    return {**defaults, **{k: v for k, v in stored.items() if k in defaults}}


def _lca_data_for(scenario: Scenario) -> OpenLCAData:
    """Return the emission factor dataset to parameterise ``scenario`` from.

    ``lca.json`` with this scenario's electricity factors in place of the file's
    per-year series. Built with :func:`dataclasses.replace` rather than by assignment:
    :func:`load_lca_defaults` is cached and hands the same object to every scenario, so
    setting the attribute would leak one scenario's grid mix into the next -- the same
    trap the battery lifetime already avoids.

    The series it substitutes has a single entry, at :func:`analysis_year`, which is
    also the year :func:`ensure_lca_parameters` samples it at. ``YearSeries.at_year``
    therefore returns it verbatim: no interpolation, and none of the clamping warnings
    a series that did not contain the year asked for would produce.
    """
    return replace(
        load_lca_defaults(),
        electricity_per_kwh=YearSeries(
            data={analysis_year(): DefaultImpactVector.from_dict(electricity_parameters(scenario))}
        ),
    )


def _ensure_station_parameters(scenario: Scenario) -> None:
    """Distribute the site-build costs onto the scenario's stations.

    These are the costs of building the charging site itself, which eflips-impact
    prices per station and groups by the value of this column. The model's
    ``db_default`` has ``procurement_cost: 0``, so without this every station would be
    free.

    Which stations are depots is only known once a :class:`~ebustoolbox.models.Depot`
    exists, and that happens during the simulation — after this has already run once on
    the MUTATION, where every station necessarily looks like an ordinary charging
    station. Since both parameter sets live on the scenario, the toolchain's second
    call simply re-runs the split and the depot stations pick up the depot values then.

    Deliberately not gated on ``tco_parameters_edited``: it copies down what
    :func:`charging_infrastructure_parameters` returns, which already respects the
    flag, and it has to keep running after the user has saved so that the depot split
    can still be applied.
    """
    parameters = charging_infrastructure_parameters(scenario)
    depot_station_ids = set(
        Depot.objects.filter(scenario=scenario).values_list("station_id", flat=True)
    )

    for station in Station.objects.filter(scenario=scenario):
        wanted = deepcopy(parameters["depot" if station.id in depot_station_ids else "station"])
        if station.tco_parameters == wanted:
            continue
        station.tco_parameters = wanted
        station.save(update_fields=["tco_parameters"])


