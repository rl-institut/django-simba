def apply_tco_mutation(mutation: Scenario, child: Scenario, stack: dict) -> None:
    """Apply the mutation's TCO data to the simulated scenario.

    Counterpart of ``apply_vehicle_mutation`` / ``apply_station_mutation``, called
    from ``create_child_from_mutation``. The child is a deepcopy of the SOURCE
    scenario, which owns none of these rows, so without this the user's cost inputs
    never reach the simulation.

    ``VehicleType.tco_parameters`` and ``Station.tco_parameters`` are already carried
    by the two functions above, which copy whole rows. That is also why the
    ``battery_type_id`` / ``charging_point_type_id`` of the child point at the
    *mutation's* rows at this point — a cross-scenario reference that would cascade
    into the simulated scenario when the mutation is deleted. Repairing those is the
    second half of this function, so it has to run after ``apply_vehicle_mutation``.

    :param mutation: The MUTATION scenario the wizard wrote to.
    :param child: The SIMULATION scenario, a deepcopy of the SOURCE.
    :param stack: Deepcopy bookkeeping, unused here but kept for signature symmetry
        with the other ``apply_*`` functions.
    """
    # Carries USER_EDITED_KEY with it, so the toolchain's own ensure_fleet_topology
    # call will not overwrite the values copied here with the JSON defaults.
    child.tco_parameters = deepcopy(mutation.tco_parameters)

    battery_type_map = {}
    for battery_type in BatteryType.objects.filter(scenario=mutation):
        old_id = battery_type.id
        battery_type.id = None
        battery_type.scenario = child
        battery_type.save()
        battery_type_map[old_id] = battery_type.id

    charging_point_type_map = {}
    for charging_point_type in ChargingPointType.objects.filter(scenario=mutation):
        old_id = charging_point_type.id
        charging_point_type.id = None
        charging_point_type.scenario = child
        charging_point_type.save()
        charging_point_type_map[old_id] = charging_point_type.id

    for vehicle_type in VehicleType.objects.filter(scenario=child, battery_type__isnull=False):
        vehicle_type.battery_type_id = battery_type_map.get(vehicle_type.battery_type_id)
        vehicle_type.save(update_fields=["battery_type"])

    for station in Station.objects.filter(scenario=child, charging_point_type__isnull=False):
        station.charging_point_type_id = charging_point_type_map.get(station.charging_point_type_id)
        station.save(update_fields=["charging_point_type"])

    logger.info(
        f"S.ID:{child.id}:Applied TCO mutation from S.ID:{mutation.id} "
        f"({len(battery_type_map)} battery types, "
        f"{len(charging_point_type_map)} charging point types)"
    )


