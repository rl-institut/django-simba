async function fetchSvgText(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error('Failed to load SVG');
  return await response.text();
}
function parseSvg(svgText) {
  const parser = new DOMParser();
  const doc = parser.parseFromString(svgText, "image/svg+xml");
  return doc.documentElement;
}
function prepareLogoSvg(svgElement, targetWidth = 40, targetHeight = 20) {
  // Get original dimensions from viewBox or width/height attributes
  let originalWidth, originalHeight;

  if (svgElement.hasAttribute('viewBox')) {
    const viewBox = svgElement.viewBox.baseVal;
    originalWidth = viewBox.width;
    originalHeight = viewBox.height;
  } else {
    originalWidth = parseFloat(svgElement.getAttribute('width')) || targetWidth;
    originalHeight = parseFloat(svgElement.getAttribute('height')) || targetHeight;
    svgElement.setAttribute('viewBox', `0 0 ${originalWidth} ${originalHeight}`);
  }

  // Remove any existing width/height attributes that might interfere
  svgElement.removeAttribute('width');
  svgElement.removeAttribute('height');

  // Clone the SVG element
  const clonedSVG = svgElement.cloneNode(true);

  // Set the desired dimensions on the cloned SVG
  clonedSVG.setAttribute('width', targetWidth);
  clonedSVG.setAttribute('height', targetHeight);

  // Create a group element for transformation
  const g = document.createElementNS('http://www.w3.org/2000/svg', 'g');

  // Apply both translation and scaling if needed
  // Here's where you add your translation (adjust these values as needed)
  g.setAttribute('transform', `translate(30, 30)`);

  // Move all child elements to the group
  while (clonedSVG.firstChild) {
    g.appendChild(clonedSVG.firstChild);
  }
  clonedSVG.appendChild(g);

  // Create a temporary container for rendering
  const tempDiv = document.createElement('div');
  tempDiv.style.position = 'absolute';
  tempDiv.style.overflow = 'hidden';
  tempDiv.style.width = `${targetWidth}px`;
  tempDiv.style.height = `${targetHeight}px`;
  tempDiv.style.left = '-9999px';
  tempDiv.appendChild(clonedSVG);
  document.body.appendChild(tempDiv);

  return {
    svg: clonedSVG,
    cleanup: () => document.body.removeChild(tempDiv)
  };
}

async function addHeaderWithSvgLogo(pdf, scenarioName, username, dateStr, svgUrl) {
  const margin = 20;
  const logoWidth = 70;
  const logoHeight = 35;
  const startY = 15;

  // Load and parse logo SVG
  const svgText = await fetchSvgText(svgUrl);
  let svgElement = parseSvg(svgText);
  const { svg: preparedSvg, cleanup } = prepareLogoSvg(svgElement, logoWidth, logoHeight);

  try {
    // Add the SVG logo at top-left
    await svg2pdf(preparedSvg, pdf, {
      x: margin,
      y: startY,
      width: logoWidth,
      height: logoHeight
    });

    // Calculate right-aligned text position
    const pageWidth = pdf.internal.pageSize.getWidth();
    const textRightMargin = margin;
    let textY = startY + 15;

    // Scenario name - bold, bigger font (right-aligned)
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(16);
    pdf.setTextColor(40);
    pdf.text(`Scenario: ${scenarioName}`, pageWidth /2 , textY, { align: 'center' });

    // "Generated by: ..." (right-aligned)
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(10);
    pdf.setTextColor(120);
    textY += 18;
    pdf.text(`Exportiert von: ${username} am ${dateStr}`, pageWidth - textRightMargin, textY, { align: 'right' });

    // Underline below header
    pdf.setDrawColor(200);
    pdf.setLineWidth(0.5);
    pdf.line(margin, startY + logoHeight +5 , pageWidth - margin, startY + logoHeight+5 );
  } finally {
    cleanup();
  }
}


function addFooter(pdf, pageNumber, totalPages) {
  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();
  pdf.setFontSize(10);
  pdf.setTextColor(150);
  pdf.line(20, pageHeight - 40, pageWidth - 20, pageHeight - 40); // line above footer
  pdf.text(`Page ${pageNumber} of ${totalPages}`, pageWidth / 2, pageHeight - 25, { align: 'center' });
}

